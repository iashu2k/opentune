"""Aggregate baseline JSONLs into the published results table.

For each (model, arm, eval_set) cell: accuracy + bootstrap 95% CI (10k
resamples over row-level correctness). McNemar exact p-values for every
arm-vs-arm pair within (model, eval_set) — the paired comparison the gate
and README need. Writes:
  results/aggregates.json      (machine-readable, CI-annotated)
  docs/baselines.md            (human table; README TL;DR links here)

Run: uv run python scripts/aggregate_results.py
"""

import glob
import json
from pathlib import Path

import numpy as np
from scipy.stats import binomtest

RAW = Path("results/raw")
AGG = Path("results/aggregates.json")
N_BOOT, SEED = 10_000, 0


def load_cells() -> dict[tuple[str, str, str], list[dict]]:
    cells: dict[tuple[str, str, str], dict[str, dict]] = {}
    for p in sorted(glob.glob(str(RAW / "*.jsonl"))):
        for line in open(p):
            r = json.loads(line)
            key = (r["model"], r["arm"], r["eval_set"])
            cells.setdefault(key, {}).setdefault(r["id"], r)  # first-write wins
    return {k: list(v.values()) for k, v in cells.items()}


def bootstrap_ci(flags: np.ndarray) -> tuple[float, float]:
    rng = np.random.default_rng(SEED)
    stats = rng.integers(0, 2, size=(N_BOOT, len(flags)))  # placeholder shape
    idx = rng.integers(0, len(flags), size=(N_BOOT, len(flags)))
    stats = flags[idx].mean(axis=1)
    return float(np.percentile(stats, 2.5)), float(np.percentile(stats, 97.5))


def mcnemar(a: dict[str, bool], b: dict[str, bool]) -> dict:
    shared = sorted(set(a) & set(b))
    b01 = sum(a[i] and not b[i] for i in shared)  # a correct, b wrong
    c01 = sum(not a[i] and b[i] for i in shared)  # a wrong, b correct
    n = b01 + c01
    p = float(binomtest(min(b01, c01), n, 0.5).pvalue) if n else 1.0
    return {"b": b01, "c": c01, "discordant": n, "p": p, "n_shared": len(shared)}


def mcnemar_key(model: str, eval_set: str, cells: dict) -> list[dict]:
    arms = [a for (m, a, s) in cells if m == model and s == eval_set]
    out = []
    for x in arms:
        for y in arms:
            if x < y:
                fx = {r["id"]: r["correct"] for r in cells[(model, x, eval_set)]}
                fy = {r["id"]: r["correct"] for r in cells[(model, y, eval_set)]}
                out.append({"arm_a": x, "arm_b": y, **mcnemar(fx, fy)})
    return out


def main() -> None:
    cells = load_cells()
    rows = []
    for (model, arm, es), recs in sorted(cells.items()):
        flags = np.array([r["correct"] for r in recs], dtype=float)
        lo, hi = bootstrap_ci(flags)
        status = {}
        for r in recs:
            status[r["status"]] = status.get(r["status"], 0) + 1
        rows.append({
            "model": model, "arm": arm, "eval_set": es, "n": len(recs),
            "acc": float(flags.mean()), "ci_lo": lo, "ci_hi": hi,
            "status_counts": status,
        })

    tests = []
    eval_sets = sorted({s for (_, _, s) in cells})
    models = sorted({m for (m, _, _) in cells})
    for m in models:
        for es in eval_sets:
            for t in mcnemar_key(m, es, cells):
                tests.append({"model": m, "eval_set": es, **t})

    AGG.write_text(json.dumps({"cells": rows, "mcnemar": tests}, indent=2))

    lines = ["# Baseline results (auto-generated by scripts/aggregate_results.py)\n",
             "| model | arm | eval set | n | acc | 95% CI (bootstrap) | extraction ok |",
             "|---|---|---|---|---|---|---|"]
    for r in rows:
        ok = r["status_counts"].get("ok", 0)
        lines.append(
            f"| {r['model']} | {r['arm']} | {r['eval_set']} | {r['n']} | "
            f"{r['acc']:.4f} | [{r['ci_lo']:.4f}, {r['ci_hi']:.4f}] | {ok}/{r['n']} |"
        )
    lines.append("\n## McNemar paired tests (arm vs arm)\n")
    lines.append("| model | eval set | A | B | b (A√B✗) | c (A✗B√) | exact p |")
    lines.append("|---|---|---|---|---|---|---|")
    for t in tests:
        lines.append(
            f"| {t['model']} | {t['eval_set']} | {t['arm_a']} | {t['arm_b']} | "
            f"{t['b']} | {t['c']} | {t['p']:.4f} |"
        )
    Path("docs/baselines.md").write_text("\n".join(lines) + "\n")

    print(f"cells: {len(rows)}  mcnemar pairs: {len(tests)}")
    for r in rows:
        print(f"  {r['model']} {r['arm']:9s} {r['eval_set']:12s} "
              f"n={r['n']:5d} acc={r['acc']:.4f} CI=[{r['ci_lo']:.4f},{r['ci_hi']:.4f}]")


if __name__ == "__main__":
    main()
